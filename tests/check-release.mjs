import assert from 'node:assert/strict';
import { readFileSync, existsSync } from 'node:fs';
const read=(path)=>readFileSync(path,'utf8');
const html=read('public/index.html');
const js=read('public/assets/app.js');
const css=read('public/assets/style.css');
for(const p of ['public/manifest.webmanifest','public/service-worker.js','public/_headers','public/assets/icons/icon.svg'])assert.ok(existsSync(p), 'Missing '+p);
for(const view of ['home','quests','chronicle','calendar','crew'])assert.ok(html.includes('id="view-'+view+'"'),'Missing view '+view);
for(const text of ['PLAYABLE DEMO','id="characterMover"','data-world-action="trail"'])assert.ok(html.includes(text),'Missing scene element '+text);
for(const label of ['function walkToPoint(','function worldAction(','localStorage','function renderCalendar'])assert.ok(js.includes(label),'Missing behavior '+label);
assert.ok(css.includes('character-walking'),'Missing walk animation');
assert.ok(html.includes('noindex'),'Search indexing guard missing');
assert.ok(!html.includes('icon-192.png'),'Stale asset reference');
console.log('Adventure Book source smoke checks passed');

const gameHtml=read('public/play/index.html');
const gameJs=read('public/play/game.js');
const gameCss=read('public/play/game.css');
for(const name of ['game-shell','worldStage','worldArt','questTease','firstRun','levelEmblem','dialogLayer'])assert.ok(gameHtml.includes(name),'Missing immersive element '+name);
for(const name of ['xp:0','tokens:0','function levelInfo','function finishQuest','function openSpot','function openQuests','function openJournal','function moveTo','function exportSave'])assert.ok(gameJs.includes(name),'Missing game logic '+name);
assert.ok(gameCss.includes('overflow:hidden'),'Fullscreen game must not page-scroll');
assert.ok(gameCss.includes('garden-unlocked'),'Level 2 scenery unlock missing');
assert.ok(!/Brandi|Devon|Ube coconut/.test(gameHtml+gameJs),'Private family content must not appear in public game source');
import {Script,createContext} from 'node:vm';
const probe=gameJs.replace(/\}\)\(\);\s*$/,'globalThis.__gameProbe={defaultState,levelInfo,questDefs,finishQuest,getState:()=>state};})();');
assert.notEqual(probe,gameJs,'Could not probe game engine');
const testEnv=createContext({document:{readyState:'loading',addEventListener(){}},localStorage:{getItem(){return null}},console,Date,Math});
new Script(probe).runInContext(testEnv);
const game=testEnv.__gameProbe;
assert.equal(game.defaultState().xp,0);
assert.equal(game.levelInfo(0).level,0);
assert.equal(game.levelInfo(59).level,0);
assert.equal(game.levelInfo(60).level,1);
assert.equal(game.levelInfo(199).level,2);
assert.equal(game.questDefs.length,4);
assert.equal(game.finishQuest('footsteps'),false,'Incomplete quest must not reward');
console.log('Immersive Evergrove game source checks passed');
